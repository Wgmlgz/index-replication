package migrations

import (
	"database/sql"
	"fmt"
	"os"
	"path/filepath"

	"github.com/pressly/goose/v3"
)

const (
	DialectPostgres = goose.DialectPostgres
	DialectSQLite   = goose.DialectSQLite3
)

func Up(db *sql.DB, dialect goose.Dialect, dir string) error {
	migrationsDir, err := resolveMigrationsDir(dir)
	if err != nil {
		return err
	}

	if err := goose.SetDialect(string(dialect)); err != nil {
		return err
	}

	if err := goose.Up(db, migrationsDir); err != nil {
		return err
	}

	if dialect == DialectPostgres {
		return ensurePostgresIdentity(db)
	}
	return nil
}

func resolveMigrationsDir(dir string) (string, error) {
	if dir != "" {
		return dir, nil
	}

	if envDir := os.Getenv("MIGRATIONS_DIR"); envDir != "" {
		return envDir, nil
	}

	wd, err := os.Getwd()
	if err != nil {
		return "", err
	}

	current := wd
	for {
		candidate := filepath.Join(current, "migrations")
		if info, err := os.Stat(candidate); err == nil && info.IsDir() {
			matches, _ := filepath.Glob(filepath.Join(candidate, "*.sql"))
			if len(matches) > 0 {
				return candidate, nil
			}
		}

		parent := filepath.Dir(current)
		if parent == current {
			break
		}
		current = parent
	}

	return "", fmt.Errorf("migrations directory not found from %s", wd)
}

func ensurePostgresIdentity(db *sql.DB) error {
	tables := []string{
		"roles",
		"users",
		"audit_logs",
		"casbin_rules",
		"user_settings",
		"user_favorite_indexes",
	}
	for _, table := range tables {
		isIdentity, err := hasIdentity(db, table, "id")
		if err != nil {
			return err
		}
		if !isIdentity {
			if _, err := db.Exec(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY", table)); err != nil {
				return err
			}
		}
		if err := resetSequence(db, table, "id"); err != nil {
			return err
		}
	}
	return nil
}

func hasIdentity(db *sql.DB, table, column string) (bool, error) {
	var isIdentity sql.NullString
	err := db.QueryRow(
		"SELECT is_identity FROM information_schema.columns WHERE table_name = $1 AND column_name = $2",
		table,
		column,
	).Scan(&isIdentity)
	if err == sql.ErrNoRows {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	return isIdentity.Valid && isIdentity.String == "YES", nil
}

func resetSequence(db *sql.DB, table, column string) error {
	var seq sql.NullString
	if err := db.QueryRow("SELECT pg_get_serial_sequence($1, $2)", table, column).Scan(&seq); err != nil {
		return err
	}
	if !seq.Valid || seq.String == "" {
		return nil
	}

	var maxID sql.NullInt64
	if err := db.QueryRow(fmt.Sprintf("SELECT MAX(%s) FROM %s", column, table)).Scan(&maxID); err != nil {
		return err
	}

	if !maxID.Valid || maxID.Int64 < 1 {
		_, err := db.Exec("SELECT setval($1::regclass, 1, false)", seq.String)
		return err
	}

	_, err := db.Exec("SELECT setval($1::regclass, $2, true)", seq.String, maxID.Int64)
	return err
}
